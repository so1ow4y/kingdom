import { test, assert } from './runner.js';
import { plural } from '../src/core/plural.js';

const F = ['изменение', 'изменения', 'изменений'];

test('plural: формы по TZ §5.3', () => {
  const cases = { 0: 'изменений', 1: 'изменение', 2: 'изменения', 4: 'изменения', 5: 'изменений', 11: 'изменений',
    12: 'изменений', 14: 'изменений', 21: 'изменение', 22: 'изменения', 25: 'изменений', 101: 'изменение',
    111: 'изменений', 112: 'изменений', 122: 'изменения' };
  for (const [n, w] of Object.entries(cases)) assert.equal(plural(+n, F), w, 'n=' + n);
});
